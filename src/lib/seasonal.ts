export function getSeasonalIngredients(date: Date = new Date()): string[] {
  return SEASONAL_BY_MONTH[date.getMonth() + 1] ?? [];
}

export function describeSeasonal(date: Date = new Date()): string {
  const month = date.getMonth() + 1;
  const items = getSeasonalIngredients(date);
  if (!items.length) return "";
  return `${month} 月苏州时令优选：${items.join("、")}`;
}
